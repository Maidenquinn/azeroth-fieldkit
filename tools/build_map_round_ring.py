"""Generate the Elwynn round-map composition: ring, curved plates and compact cartouches (all procedural, anti-aliased, no stretched art).

Colours are those of the approved Elwynn frame art: gold 198/144/62 with highlights up to 245/226/157, bronze 112/85/36,
dark outline 32/27/7, field green 11/26/14.

map_round_ring.tga      256x256  ring around the round native map. Opening radius 113, outer radius 128 (drawn at side*128/113).
                        Directional light (bright upper left, bronze lower right), a beaded engraving in the band, a dark groove,
                        a dark green band, a thin gold line at the map edge and four diamond studs.
map_round_medallion.tga 512x512  the same ring with a header banner and a foot banner (224x32, corners cut like the zone material) crossing it: ONE piece.
elwynn_cartouche.tga    256x64   compact banner 240x36, same family (native map presentation), drawn at the top left.
"""
from pathlib import Path
import json, hashlib
import numpy as np
from PIL import Image
from scipy import ndimage

base = Path(__file__).resolve().parent.parent
out = base / 'AzerothFieldKit/media/ReferenceHUD'
S = 4
DARK = np.array([32, 27, 7.]); GREEN = np.array([18, 40, 26.]); GOLD = np.array([198, 144, 62.])
HI = np.array([240, 208, 128.]); LO = np.array([112, 85, 36.]); SHINE = np.array([245, 226, 157.])
manifest = base / 'data/theme-assets.json'
m = json.loads(manifest.read_text(encoding='utf-8'))

def down(arr, w, h):
    return arr.reshape(h, S, w, S, *arr.shape[2:]).mean(axis=(1, 3))

def finish(img, w, h):
    a = img[..., 3] / 255.0
    A = down(a, w, h); R = down(img[..., :3] * a[..., None], w, h)
    rgb = np.where(A[..., None] > 0, R / np.maximum(A[..., None], 1e-6), 0)
    return np.dstack([np.clip(rgb, 0, 255), A * 255]).round().astype('uint8')

def save(name, tile, source):
    target = out / name
    Image.fromarray(tile, 'RGBA').save(target)
    raw = target.read_bytes()
    m['files']['media/ReferenceHUD/' + name] = {'sha256': hashlib.sha256(raw).hexdigest(), 'bytes': len(raw), 'source': source}
    print(name, len(raw), 'bytes')

def paint(img, mask, col):
    img[mask, :3] = col[mask] if getattr(col, 'ndim', 1) == 3 else col
    img[mask, 3] = 255

def bevel(t):  # t 0 (outer edge) .. 1 (inner edge) -> colour
    return np.where(t < .35, HI + (GOLD - HI) * (t / .35), GOLD + (LO - GOLD) * ((t - .35) / .65))

# ---------------------------------------------------------------- ring
N = 256
c = N * S / 2.0
y, x = np.mgrid[0:N * S, 0:N * S]
yy, xx = (y + .5 - c) / S, (x + .5 - c) / S
r = np.sqrt(xx ** 2 + yy ** 2)
theta = np.arctan2(yy, xx)
img = np.zeros((N * S, N * S, 4))
paint(img, (r >= 126.5) & (r < 128), DARK)
band = (r >= 118) & (r < 126.5)
t = np.clip((126.5 - r) / 8.5, 0, 1)
light = np.cos(theta + np.radians(135)) * .5 + .5          # 1 at the upper left, 0 at the lower right
col = bevel(t[..., None]) * (.72 + .36 * light[..., None]) # directional lighting over the bevel
paint(img, band, np.clip(col, 0, 255))
bead_r = 122.2                                             # beaded engraving along the middle of the band: a dark dot every 6 degrees
for k in range(60):
    a = np.radians(k * 6.0 + 3)
    bx, by = bead_r * np.cos(a), bead_r * np.sin(a)
    paint(img, ((xx - bx) ** 2 + (yy - by) ** 2) <= 1.05 ** 2, DARK * 1.6)
paint(img, (r >= 116.5) & (r < 118), DARK)
paint(img, (r >= 114.5) & (r < 116.5), GREEN)
paint(img, (r >= 113) & (r < 114.5), GOLD)
for ang in (0, 90, 180, 270):
    a_ = np.radians(ang); ux, uy = np.cos(a_), np.sin(a_)
    du = xx * ux + yy * uy - 122.25; dv = -xx * uy + yy * ux
    paint(img, (np.abs(du) + np.abs(dv) <= 7.5) & (r < 128), DARK)
    paint(img, (np.abs(du) + np.abs(dv) <= 5.5) & (r < 128), SHINE)
save('map_round_ring.tga', finish(img, N, N), 'Generated by tools/build_map_round_ring.py: Elwynn ring (directional bevel, beaded engraving, dark groove, green band, gold line, four studs); colours sampled from the approved Elwynn frame art; no original art is altered.')

# ---------------------------------------------------------------- banners (shared by the medallion and the native cartouches)
def chamfer_mask(px, py, x0, y0, w, h, c):
    """Rectangle with its four corners cut diagonally (the corner cut of the Elwynn zone material), c = cut size in px."""
    inx = (px >= x0) & (px <= x0 + w) & (py >= y0) & (py <= y0 + h)
    dx = np.minimum(px - x0, x0 + w - px); dy = np.minimum(py - y0, y0 + h - py)
    return inx & (dx + dy >= c)

def paint_banner(img, shape, py, y0, h):
    d = ndimage.distance_transform_edt(shape) / S
    paint(img, shape, DARK)                                                # outer dark outline
    gt = np.clip((d - 1.2) / 2.6, 0, 1)                                    # bevelled gold border, lit from above
    lightp = np.clip(1.0 - (py - y0) / (h * 1.6), .62, 1.0)[..., None]
    paint(img, shape & (d > 1.2), np.clip(bevel(gt[..., None] * .9) * lightp, 0, 255))
    paint(img, shape & (d > 3.8), DARK)                                    # dark groove
    paint(img, shape & (d > 4.8), GREEN * (1.08 - .38 * ((py - y0) / h))[..., None])   # field green, slightly lighter at the top
    paint(img, shape & (d > 4.8) & (d < 5.7), GOLD * .85)                  # fine inner gold line

# ---------------------------------------------------------------- medallion: ring + header banner + foot banner, one texture
N = 512
c = N * S / 2.0
y, x = np.mgrid[0:N * S, 0:N * S]
yy, xx = (y + .5 - c) / S, (x + .5 - c) / S
r = np.sqrt(xx ** 2 + yy ** 2)
theta = np.arctan2(yy, xx)
img = np.zeros((N * S, N * S, 4))
paint(img, (r >= 126.5) & (r < 128), DARK)
t = np.clip((126.5 - r) / 8.5, 0, 1)
light = np.cos(theta + np.radians(135)) * .5 + .5
paint(img, (r >= 118) & (r < 126.5), np.clip(bevel(t[..., None]) * (.72 + .36 * light[..., None]), 0, 255))
for k in range(60):
    a = np.radians(k * 6.0 + 3)
    paint(img, ((xx - 122.2 * np.cos(a)) ** 2 + (yy - 122.2 * np.sin(a)) ** 2) <= 1.05 ** 2, DARK * 1.6)
paint(img, (r >= 116.5) & (r < 118), DARK)
paint(img, (r >= 114.5) & (r < 116.5), GREEN)
paint(img, (r >= 113) & (r < 114.5), GOLD)
for ang in (0, 180):                                                        # side studs only: the banners take the top and the bottom
    a_ = np.radians(ang); ux, uy = np.cos(a_), np.sin(a_)
    du = xx * ux + yy * uy - 122.25; dv = -xx * uy + yy * ux
    paint(img, (np.abs(du) + np.abs(dv) <= 7.5) & (r < 128), DARK)
    paint(img, (np.abs(du) + np.abs(dv) <= 5.5) & (r < 128), SHINE)
BW, BH, CUT, MID = 224.0, 32.0, 8.0, 121.0                                  # banner: 224 x 32, corners cut 8, centred on the ring band (radius 121)
for sign in (-1, 1):
    shape = chamfer_mask(xx, yy, -BW / 2, sign * MID - BH / 2, BW, BH, CUT)
    paint_banner(img, shape, yy, sign * MID - BH / 2, BH)
    for ex in (-1, 1):                                                       # a small gold stud at each end of the banner
        sx, sy = ex * (BW / 2 - 12), sign * MID
        paint(img, (np.abs(xx - sx) + np.abs(yy - sy)) <= 3.6, SHINE)
save('map_round_medallion.tga', finish(img, N, N), 'Generated by tools/build_map_round_ring.py: Elwynn round-map medallion (ring with its header and foot banners cut like the zone material corners) in one 512x512 texture; ring centre (256,256), opening radius 113, banners 224x32 centred on radius 121.')

# ---------------------------------------------------------------- compact cartouche (native presentation), same banner family
W, H = 256, 64
y, x = np.mgrid[0:H * S, 0:W * S]
px, py = (x + .5) / S, (y + .5) / S
CW, CH = 240.0, 36.0
img = np.zeros((H * S, W * S, 4))
paint_banner(img, chamfer_mask(px, py, 0, 0, CW, CH, 8.0), py, 0, CH)
for ex in (12, CW - 12):
    paint(img, (np.abs(px - ex) + np.abs(py - CH / 2)) <= 3.6, SHINE)
save('elwynn_cartouche.tga', finish(img, W, H), 'Generated by tools/build_map_round_ring.py: compact Elwynn cartouche 240x36 (same banner family and corner cut as the medallion) at the top left of a 256x64 texture, for the native-map presentation.')

# the curved plates of alpha.45 are gone
old = out / 'map_round_plate.tga'
if old.exists(): old.unlink()
m['files'].pop('media/ReferenceHUD/map_round_plate.tga', None)
manifest.write_bytes((json.dumps(m, indent=2) + '\n').encode('utf-8'))
